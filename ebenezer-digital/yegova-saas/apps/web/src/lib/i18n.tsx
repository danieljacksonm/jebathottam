/** Turn API / network errors into simple shop-owner language. */
export function friendlyError(
  err: unknown,
  t: TFn,
  fallback: keyof typeof en = 'err_generic',
): string {
  const raw =
    err instanceof Error
      ? err.message.trim()
      : typeof err === 'string'
        ? err.trim()
        : '';
  if (!raw) return t(fallback);
  if (API_MSG_MAP[raw]) return t(API_MSG_MAP[raw]);
  const lower = raw.toLowerCase();
  if (
    lower.includes('failed to fetch') ||
    lower.includes('network') ||
    lower.includes('load failed')
  ) {
    return t('err_network');
  }
  if (lower === 'unauthorized' || lower.includes('jwt')) {
    return t('err_session');
  }
  // Keep short plain messages; swap generic English fallbacks
  if (/^(failed|error|internal server error)$/i.test(raw)) {
    return t(fallback);
  }
  return raw;
}

