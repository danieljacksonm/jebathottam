async function main() {
  let updated = 0;
  let missing = [];
  for (const [slug, { ta, hi }] of Object.entries(bodies)) {
    const existing = await prisma.blogPost.findUnique({ where: { slug } });
    if (!existing) {
      missing.push(slug);
      continue;
    }
    await prisma.blogPost.update({
      where: { slug },
      data: {
        bodyTa: paras(...ta),
        bodyHi: paras(...hi),
        featured: true,
        status: "published",
      },
    });
    updated += 1;
  }
  console.log(`Updated TA/HI bodies for ${updated} guides`);
  if (missing.length) console.log("Missing slugs:", missing.join(", "));
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
