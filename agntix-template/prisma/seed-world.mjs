/** Merge destination places with default place catalogue. */
export function placesForDestination(dest) {
  const listed = dest.places ?? [];
  const defaults = DEFAULT_PLACES[dest.slug] ?? [];
  const bySlug = new Map();
  for (const place of [...listed, ...defaults]) {
    if (!bySlug.has(place.slug)) bySlug.set(place.slug, place);
  }
  return [...bySlug.values()];
}

